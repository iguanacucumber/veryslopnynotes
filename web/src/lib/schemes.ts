// Palettes de couleurs (#335). Source UNIQUE : l'aperçu des réglages et les
// variables CSS appliquées sur `<html>` sortent du même objet, donc jamais de
// dérive entre ce qui est montré et ce qui est rendu.
//
// Chaque palette porte une variante claire ET sombre : le mode (Système/Clair/
// Sombre) choisit la variante, la palette choisit la famille. Les teintes
// viennent des palettes officielles des projets cités (valeurs seules, aucun
// asset copié) ; quelques variantes claires de thèmes sombres sont dérivées et
// le disent. Les paires encre/surface et accent/fond sont tenues par
// `tests/web/schemes.test.ts` (contraste ≥ 4.5:1).

export interface Palette {
  /** Fond de page. */
  page: string;
  /** Cartes et barres. */
  surface: string;
  /** Survols discrets, fonds secondaires. */
  surfaceVariant: string;
  /** Badges et pastilles. */
  surfaceContainer: string;
  /** Encre principale (texte lisible). */
  ink: string;
  /** Accent : bordures actives, spinner, remplissages `.field:focus`. */
  brand: string;
  /** Accent clair : anneaux de focus, dégradés. */
  brandLight: string;
  /** Accent lisible sur page/surface : liens, onglet actif, icônes. */
  brandDeep: string;
  /** Accent très pâle : fond de puce/onglet actif. */
  brandPale: string;
  /** Fond plein (bouton principal). */
  brandSolid: string;
  /** Texte posé sur `brandSolid`. */
  onBrand: string;
  /** Rouge de signalement : bordures, teintes. */
  danger: string;
  /** Fond plein d'action destructive. */
  dangerSolid: string;
  /** Texte posé sur `dangerSolid`. */
  onDanger: string;
  /** Rouge lisible sur page/surface (messages d'erreur). */
  dangerInk: string;
}

export interface Scheme {
  id: string;
  label: string;
  light: Palette;
  dark: Palette;
}

